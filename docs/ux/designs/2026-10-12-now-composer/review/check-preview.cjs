const { chromium } = require('C:/Users/chens/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  const out='D:/Project/birdtie/docs/ux/designs/2026-10-12-now-composer/review';
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const errors=[],checks=[];
  const page=await browser.newPage({viewport:{width:900,height:1120},deviceScaleFactor:1});
  page.on('pageerror',err=>errors.push(err.message));
  await page.goto('http://127.0.0.1:8763/',{waitUntil:'networkidle'});
  const frame=page.frameLocator('iframe');
  await frame.locator('.bt-phone').waitFor();
  await frame.locator('.bt-chrome svg.lucide').first().waitFor({timeout:30000});
  const shot=async(name)=>frame.locator('#birdtie-now-preview').screenshot({path:path.join(out,name+'.png')});
  const scene=async(name)=>{if(['map','input','answer','reading'].includes(name))await frame.locator('[data-scene="'+name+'"]').click();else await frame.locator('#bt-more-scenes').selectOption(name);await page.waitForTimeout(200);};
  await shot('desktop-map');
  for (const name of ['input','attachments','mention','answer','reading','draft','empty','error']) {await scene(name);await shot('desktop-'+name);}
  await scene('input');
  const editor=frame.locator('#bt-input');
  await editor.fill('保留我的输入');
  await frame.locator('[data-action="plus"]').click();
  await frame.locator('[data-action="plus"]').click();
  checks.push({name:'菜单返回保留输入',passed:await editor.inputValue()==='保留我的输入'});
  await frame.locator('[data-action="voice"]').click();
  await frame.locator('.bt-modal [data-action="dismiss"]').first().click();
  checks.push({name:'语音取消保留原稿',passed:await editor.inputValue()==='保留我的输入'});
  await frame.locator('[data-action="voice"]').click();
  await frame.locator('[data-action="finish-voice"]').click();
  checks.push({name:'转写填稿未自动发送',passed:(await editor.inputValue()).includes('散步')&&!(await frame.locator('.bt-sheet').getAttribute('class')).includes('has-result')});
  await editor.fill('海事博物馆在哪里');
  await frame.locator('[data-action="send"]').click();
  await page.waitForTimeout(1200);
  checks.push({name:'手动提交展示同地点卡',passed:await frame.locator('.bt-place-card').count()===1});
  await scene('reading');
  await frame.locator('.bt-result-content').evaluate(el=>el.scrollTop=240);
  await frame.locator('[data-action="close-result"]').click();
  await frame.locator('[data-action="sidebar"]').click();
  await frame.locator('[data-action="resume-task"]').click();
  checks.push({name:'回地图后恢复阅读位置',passed:await frame.locator('.bt-result-content').evaluate(el=>el.scrollTop)>150});
  await scene('draft');
  await frame.locator('#bt-draft-body').fill('这是一份可编辑的演示草稿');
  await frame.locator('[data-action="audience"]').click();
  await frame.locator('[data-action="audience-friends"]').click();
  await frame.locator('[data-action="preview-draft"]').click();
  checks.push({name:'预览明确正文与受众',passed:(await frame.locator('.bt-modal').innerText()).includes('这是一份可编辑的演示草稿')&&(await frame.locator('.bt-modal').innerText()).includes('好友')});
  await frame.locator('.bt-modal [data-action="dismiss"]').first().click();
  await frame.locator('[data-action="draft-place"]').click();
  await frame.locator('[data-action="draft-place-demo"]').click();
  await frame.locator('[data-action="preview-draft"]').click();
  checks.push({name:'选中地点进入草稿字段及预览',passed:(await frame.locator('.bt-modal').innerText()).includes('海事博物馆 · 演示')});
  await frame.locator('.bt-modal [data-action="dismiss"]').first().click();
  await scene('answer');
  checks.push({name:'短回答导航与来源完整可见',passed:await frame.locator('.bt-phone').evaluate(el=>{const a=el.querySelector('.bt-place-footer').getBoundingClientRect(),b=el.querySelector('.bt-composer-wrap').getBoundingClientRect();return a.bottom<=b.top&&a.height>=44;})});
  await page.setViewportSize({width:392,height:1120});
  for(const name of ['map','input','attachments','mention','answer','reading','draft']) {if(name==='attachments')await scene('input');await scene(name);await shot('mobile-'+name);}
  const mobileFrame=page.frames().find(f=>f.parentFrame());
  checks.push({name:'窄屏无横向溢出',passed:await mobileFrame.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)});
  await scene('input');
  checks.push({name:'输入面板贴键盘边缘',passed:await frame.locator('.bt-phone').evaluate(el=>{const a=el.querySelector('.bt-sheet').getBoundingClientRect(),b=el.querySelector('.bt-keyboard').getBoundingClientRect();return Math.abs(a.bottom-b.top)<1;})});
  await page.setViewportSize({width:352,height:1120});
  await scene('reading');await shot('narrow-reading');
  await mobileFrame.evaluate(()=>{const root=document.getElementById('birdtie-now-preview');root.querySelector('.bt-result-content').style.fontSize='30px';root.querySelectorAll('.bt-composer textarea').forEach(el=>{el.style.fontSize='32px';el.style.lineHeight='42px';el.dispatchEvent(new Event('input',{bubbles:true}));});});
  await shot('large-text-reading');
  checks.push({name:'大文字正文与输入可滚动',passed:await frame.locator('.bt-phone').evaluate(el=>{const c=el.querySelector('.bt-result-content');return c.scrollHeight>c.clientHeight&&el.querySelector('.bt-send').getBoundingClientRect().right<=el.getBoundingClientRect().right;})});
  await page.setViewportSize({width:900,height:1120});
  await page.emulateMedia({colorScheme:'dark'});
  await page.reload({waitUntil:'networkidle'});
  await scene('map');await shot('dark-map');
  await scene('input');await shot('dark-input');
  await scene('reading');await shot('dark-reading');
  const report={errors,checks,passed:errors.length===0&&checks.every(c=>c.passed),scope:'浏览器设计原型；非原生产品验收'};
  fs.writeFileSync(path.join(out,'verification.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
  await browser.close();
})();
